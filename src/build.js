// Derives palettes, accessibility metadata, CSS variables and design tokens
// from colors.json. Run with `npm run build`; no dependencies required.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');

// WCAG 2.x thresholds
const AA = 4.5;
const AA_LARGE = 3;
const AAA = 7;

// Tag thresholds, applied to CIE LCh (derived from the D50 L*a*b* values)
const NEUTRAL_CHROMA = 10;
const LIGHT_L = 70;
const DARK_L = 35;
const VIVID_CHROMA = 50;
const PASTEL_MAX_CHROMA = 40;
const MUTED_MAX_CHROMA = 25;

const round = (n, digits) => {
  const f = Math.pow(10, digits);
  return Math.round(n * f) / f;
};

function slugify (name) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function hexToRgb (hex) {
  const n = parseInt(hex.slice(1), 16);
  return [ (n >> 16) & 255, (n >> 8) & 255, n & 255 ];
}

// https://www.w3.org/TR/WCAG21/#dfn-relative-luminance
function luminance (hex) {
  const [ r, g, b ] = hexToRgb(hex).map(v => {
    const c = v / 255;
    return c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

// https://www.w3.org/TR/WCAG21/#dfn-contrast-ratio
function contrast (hexA, hexB) {
  const la = luminance(hexA);
  const lb = luminance(hexB);
  return (Math.max(la, lb) + 0.05) / (Math.min(la, lb) + 0.05);
}

function labToLch ([ L, a, b ]) {
  const C = Math.sqrt(a * a + b * b);
  let H = Math.atan2(b, a) * 180 / Math.PI;
  if (H < 0) H += 360;
  return [ L, C, H ];
}

function tagsFor ([ L, C, H ]) {
  const tags = [];
  if (C < NEUTRAL_CHROMA) tags.push('neutral');
  else if (H >= 330 || H < 90) tags.push('warm');
  else if (H >= 150 && H < 300) tags.push('cool');

  if (L >= LIGHT_L) tags.push('light');
  else if (L <= DARK_L) tags.push('dark');

  if (C >= VIVID_CHROMA) tags.push('vivid');
  else if (L >= LIGHT_L && C >= NEUTRAL_CHROMA && C < PASTEL_MAX_CHROMA) tags.push('pastel');
  else if (L < LIGHT_L && C >= NEUTRAL_CHROMA && C < MUTED_MAX_CHROMA) tags.push('muted');
  return tags;
}

function contrastPair (colors, a, b) {
  const ratio = contrast(colors[a].hex, colors[b].hex);
  return {
    a,
    b,
    ratio: round(ratio, 2),
    aa: ratio >= AA,
    aaLarge: ratio >= AA_LARGE,
    aaa: ratio >= AAA
  };
}

function buildPalettes (colors) {
  const map = new Map();
  colors.forEach((color, i) => {
    color.combinations.forEach(id => {
      if (map.has(id)) map.get(id).push(i);
      else map.set(id, [ i ]);
    });
  });

  return [ ...map.entries() ]
    .sort((a, b) => a[0] - b[0])
    .map(([ id, indices ]) => {
      const pairs = [];
      for (let i = 0; i < indices.length; i++) {
        for (let j = i + 1; j < indices.length; j++) {
          pairs.push(contrastPair(colors, indices[i], indices[j]));
        }
      }
      return {
        id,
        size: indices.length,
        colors: indices,
        names: indices.map(i => colors[i].name),
        hex: indices.map(i => colors[i].hex),
        contrast: pairs
      };
    });
}

function buildMeta (colors) {
  return colors.map((color, index) => {
    const lch = labToLch(color.lab);
    const onWhite = contrast(color.hex, '#ffffff');
    const onBlack = contrast(color.hex, '#000000');
    return {
      index,
      name: color.name,
      slug: slugify(color.name),
      hex: color.hex,
      luminance: round(luminance(color.hex), 4),
      lch: lch.map(n => round(n, 2)),
      contrastOnWhite: round(onWhite, 2),
      contrastOnBlack: round(onBlack, 2),
      textColor: onBlack >= onWhite ? '#000000' : '#ffffff',
      tags: tagsFor(lch)
    };
  });
}

function buildCss (colors) {
  const lines = colors.map(c => `  --sanzo-${slugify(c.name)}: ${c.hex};`);
  return `/* Generated by src/build.js – do not edit by hand */\n:root {\n${lines.join('\n')}\n}\n`;
}

function buildTokens (colors) {
  const sanzo = {};
  colors.forEach(c => {
    sanzo[slugify(c.name)] = {
      $type: 'color',
      $value: c.hex,
      $description: c.name
    };
  });
  return { sanzo };
}

const toJson = data => JSON.stringify(data, null, 2) + '\n';

function buildAll (colors) {
  return {
    'palettes.json': toJson(buildPalettes(colors)),
    'meta.json': toJson(buildMeta(colors)),
    'colors.css': buildCss(colors),
    'tokens.json': toJson(buildTokens(colors))
  };
}

module.exports = {
  slugify,
  luminance,
  contrast,
  labToLch,
  tagsFor,
  buildPalettes,
  buildMeta,
  buildCss,
  buildTokens,
  buildAll
};

if (require.main === module) {
  const colors = require(path.join(root, 'colors.json'));
  const outputs = buildAll(colors);
  Object.keys(outputs).forEach(file => {
    fs.writeFileSync(path.join(root, file), outputs[file]);
    console.log('Wrote', file);
  });
}
